export const slashBaseSeedRows: SlashBaseSeedRow[] = [
  ...parseSlashBaseSeedLedger(phaseBLedger, { expectedRows: 22 }),
  ...parseSlashBaseSeedLedger(matrixLedger, { expectedRows: 88 }),
];

export const slashBaseCards = pairSeedRows(slashBaseSeedRows);

function pairSeedRows(rows: SlashBaseSeedRow[]): SlashBaseCard[] {
  const byKey = new Map<string, Partial<Record<"original" | "delivered", SlashBaseSeedRow>>>();
  for (const row of rows) {
    const key = `${row.preset}:${row.imageName}`;
    const pair = byKey.get(key) ?? {};
    pair[row.side] = row;
    byKey.set(key, pair);
  }

  return [...byKey.entries()].map(([key, pair]) => {
    const [preset, imageName] = key.split(":");
    if (!pair.original || !pair.delivered) {
      throw new Error(`SlashBase is missing a before/after pair for ${key}.`);
    }
    const original = originalAssets[imageName];
    const delivered = deliveredAssets[key];
    if (!original) throw new Error(`SlashBase is missing original assets for ${imageName}.`);
    if (!delivered) throw new Error(`SlashBase is missing delivered assets for ${key}.`);
    if (pair.original.sequenceCode !== pair.delivered.sequenceCode) {
      throw new Error(`SlashBase found mismatched SEQ codes for ${key}.`);
    }

    return {
      id: key,
      imageName,
      preset: pair.delivered.preset,
      sequenceCode: pair.delivered.sequenceCode,
      timestamp: pair.delivered.timestamp,
      original: {
        fileName: pair.original.fileName,
        imageUrl: original,
        grade: pair.original.grade,
        timestamp: pair.original.timestamp,
      },
      delivered: {
        fileName: pair.delivered.fileName,
        imageUrl: delivered,
        grade: pair.delivered.grade,
        timestamp: pair.delivered.timestamp,
      },
    };
  });
}
